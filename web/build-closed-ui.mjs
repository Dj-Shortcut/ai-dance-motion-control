// intercept routing and prevent the direct Access context from reaching it.
import {readFile,writeFile} from 'node:fs/promises';
const names=['index.html','style.css','media.js','app.js','payments.js','generation-ui.js','auth-bundle.js'];
const files=Object.fromEntries(await Promise.all(names.map(async name=>[`/multiuser/${name}`,await readFile(new URL(`./frontend/multiuser/${name}`,import.meta.url),'utf8')])));
await writeFile(new URL('./closed-ui-bundle.mjs',import.meta.url),`// Generated by build-closed-ui.mjs. Do not edit.\nexport default ${JSON.stringify(files)};\n`);
