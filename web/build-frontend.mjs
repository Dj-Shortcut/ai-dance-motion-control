// Bundle this exact checked-in owner-test UI into the Worker script itself.
// Do not configure Cloudflare Static Assets: its router drops ctx.access.
import {readFile,writeFile} from 'node:fs/promises';
const names=['index.html','style.css','app.js','media.js','payments.js','generation-ui.js','media-test.html','media-test.js'];
const assets=Object.fromEntries(await Promise.all(names.map(async name=>['/'+name,await readFile(new URL('./frontend/'+name,import.meta.url),'utf8')])));
await writeFile(new URL('./frontend-bundle.mjs',import.meta.url),'// Generated by build-frontend.mjs. Do not edit.\nexport default '+JSON.stringify(assets)+';\n');
